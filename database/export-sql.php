<?php

declare(strict_types=1);

/*
 * Writes database/seed.sql: the schema plus the demo data from database/mock,
 * ready to import in Adminer on a server without command line access.
 * With a data folder it exports that JSON storage instead, e.g. live data downloaded from the server
 * (keep that file out of git, it contains e-mails and password hashes).
 * Usage: php database/export-sql.php [DATA_DIR OUTPUT_FILE]
 */

use App\Core\App;
use App\Storage\JsonStore;

require_once dirname(__DIR__) . '/src/bootstrap.php';

$source = $argv[1] ?? null;
$output = $argv[2] ?? __DIR__ . '/seed.sql';

if ($source !== null) {
    if (!is_dir($source) || !isset($argv[2])) {
        fwrite(STDERR, "Usage: php database/export-sql.php [DATA_DIR OUTPUT_FILE]\n");
        exit(1);
    }

    $store = new JsonStore($source);
} else {
    // Run the regular seed into a temporary JSON store, then turn its rows into INSERTs.
    $dir = sys_get_temp_dir() . '/seed-export-' . uniqid();
    $_ENV['DATA_DRIVER'] = 'json';
    App::set('store', $store = new JsonStore($dir));

    ob_start();
    require __DIR__ . '/seed.php';
    ob_end_clean();
}

$value = fn (mixed $v) => match (true) {
    $v === null => 'NULL',
    is_bool($v) => $v ? '1' : '0',
    is_int($v), is_float($v) => (string) $v,
    default => "'" . str_replace(['\\', "'"], ['\\\\', "''"], (string) $v) . "'",
};

$insert = function (string $table, array $columns, array $rows) use ($value): string {
    if ($rows === []) {
        return '';
    }

    $values = array_map(
        fn (array $row) => '(' . implode(', ', array_map(fn (string $column) => $value($row[$column] ?? null), $columns)) . ')',
        $rows
    );

    return "INSERT INTO {$table} (" . implode(', ', $columns) . ") VALUES\n" . implode(",\n", $values) . ";\n\n";
};

$items = array_values($store->all('items'));
$photos = array_map(
    fn (array $item) => ['item_id' => $item['id'], 'path' => $item['photo']],
    array_filter($items, fn (array $item) => $item['photo'] !== null)
);

$sql = "-- Generated by database/export-sql.php, do not edit. Import in Adminer (recreates all tables).\n\n"
    . "SET NAMES utf8mb4;\n\n"
    . file_get_contents(__DIR__ . '/schema.sql') . "\n"
    . $insert('users', ['id', 'name', 'email', 'password_hash', 'role', 'is_blocked', 'created_at'], array_values($store->all('users')))
    . $insert('categories', ['id', 'slug', 'name'], array_values($store->all('categories')))
    . $insert('buildings', ['id', 'slug', 'name', 'short', 'lat', 'lng'], array_values($store->all('buildings')))
    . $insert('items', ['id', 'user_id', 'category_id', 'building_id', 'type', 'status', 'title', 'slug', 'description', 'search_text', 'location', 'lat', 'lng', 'date', 'created_at', 'updated_at'], $items)
    . $insert('photos', ['item_id', 'path'], array_values($photos))
    . $insert('messages', ['id', 'item_id', 'sender_id', 'body', 'created_at'], array_values($store->all('messages')));

file_put_contents($output, rtrim($sql) . "\n");

if (isset($dir)) {
    exec('rm -rf ' . escapeshellarg($dir));
}

echo "Written {$output}\n";
